export function glyph(ch: string): string[] {
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT["?"]!;
}

/** Pixel width of a string at the given scale, including 1px inter-glyph gap. */
export function textWidth(text: string, scale: number): number {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + 1) * scale - scale;
}
